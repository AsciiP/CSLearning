def stirling(n: int, k: int) -> int:
    """
    计算第二类斯特林数 S(n, k)。
    
    递推关系: S(n, k) = k * S(n-1, k) + S(n-1, k-1)
    边界条件: S(0, 0) = 1, S(n, n) = 1, S(n, 1) = 1，其他越界情况为 0
    
    参数:
        n: 元素总数（非负整数）
        k: 集合数量（非负整数）
    
    返回:
        将 n 个不同元素划分为 k 个非空无序集合的方案数
    """
    # 处理越界输入
    if n < 0 or k < 0 or k > n:
        return 0
    if n == 0 and k == 0:
        return 1
    # 边界条件：每个元素单独成一组，或所有元素放入同一组
    if k == 1 or k == n:
        return 1

    # 只保留当前行，避免保存不再使用的历史结果
    dp = [0] * (k + 1)
    dp[0] = 1

    # 从右向左更新，确保 dp[j - 1] 仍是上一行的值
    for i in range(1, n + 1):
        for j in range(min(i, k), 0, -1):
            dp[j] = j * dp[j] + dp[j - 1]
        dp[0] = 0

    return dp[k]


