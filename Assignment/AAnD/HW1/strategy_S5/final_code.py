"""
【算法思想概览】
第二类斯特林数 S(n, k)：把 n 个「互不相同」的球，放进 k 个「完全相同」的盒子，
要求每个盒子非空，共有多少种放法？（盒子无序 ⇒ 不能简单用 k^n 去重）

核心思路：盯住最后一个球（第 n 个球），它只有两种去向 ——
  A) 挤进已有的某个盒子里：前 n-1 个球已占满 k 个盒子（S(n-1,k) 种），
     第 n 个球有 k 个盒子可选 ⇒ 贡献 k * S(n-1, k)
  B) 自己单独住一个新盒子：前 n-1 个球只能占 k-1 个盒子 ⇒ 贡献 S(n-1, k-1)
两者相加即得递推式：S(n,k) = k*S(n-1,k) + S(n-1,k-1)

实现方式：自底向上的动态规划。从 S(0,0)=1 出发，逐行把三角表填到第 n 行。
边界：S(0,0)=1；n>0 时 S(n,0)=0；k>n 时 S(n,k)=0；S(n,n)=1（由递推自然得出）。
"""


def stirling2_teaching(n: int, k: int) -> int:
    # ---------- 0. 参数合法性守卫：数学上不可能的情况直接返回 0 ----------
    if n < 0 or k < 0:          # 负数无定义
        return 0
    if k > n:                   # 盒子比球多，必有空盒 ⇒ 0 种
        return 0
    if k == 0:                  # 没有盒子：只有「也没有球」时算 1 种（空划分）
        return 1 if n == 0 else 0

    # ---------- 1. 建表：开 (n+1) x (k+1)，让数组下标 = 数学下标 ----------
    # ⚠️ 注意：必须多开一行一列！数学上要访问 S[n][k]，若开 n x k 会越界
    S = [[0] * (k + 1) for _ in range(n + 1)]

    # ---------- 2. 设定唯一种子：S(0,0) = 1 ----------
    # ⚠️ 注意：这是整张表的「唯一起点」。若漏掉这一行，后面全部是 0+0=0
    S[0][0] = 1

    # ---------- 3. 逐行填表：i = 当前球的个数（从 1 到 n）----------
    for i in range(1, n + 1):
        # j = 当前盒子的个数。上界取 min(i, k)：
        # 盒子数不可能超过球数，超过的部分恒为 0，不必计算
        for j in range(1, min(i, k) + 1):
            # ---------- 4. 核心递推：两种去向相加 ----------
            # j * S[i-1][j]   ：第 i 个球加入已有的 j 个盒子之一（j 种选择）
            # S[i-1][j-1]     ：第 i 个球独占一个新盒子，其余 i-1 个球占 j-1 盒
            # ⚠️ 注意：这里用的是「上一行」i-1 的值，所以外层 i 必须从小到大走
            S[i][j] = j * S[i - 1][j] + S[i - 1][j - 1]

    # ---------- 5. 答案就在表的右下角 ----------
    return S[n][k]


# ==================== 自测：跑完这三条，基本可以放心 ====================
if __name__ == "__main__":
    # ① S(n, n) = 1：每球一盒，只有一种
    assert all(stirling2_teaching(n, n) == 1 for n in range(1, 8))

    # ② S(n, 2) = 2^(n-1) - 1：把 n 个球分成两堆（无序）
    for n in range(2, 8):
        assert stirling2_teaching(n, 2) == 2 ** (n - 1) - 1

    # ③ 题目要求的五组典型输入
    expected_values = {
        (3, 2): 3,
        (4, 2): 7,
        (5, 3): 25,
        (6, 3): 90,
        (10, 4): 34105,
    }
    for (n, k), expected in expected_values.items():
        assert stirling2_teaching(n, k) == expected

    # ④ 边界防御
    assert stirling2_teaching(5, 6) == 0
    assert stirling2_teaching(0, 0) == 1
    assert stirling2_teaching(3, 0) == 0

    # ⑤ 打印小三角，直观感受结构（贝尔数 = 每行之和）
    N = 7
    tbl = [[0] * (N + 1) for _ in range(N + 1)]
    tbl[0][0] = 1
    for i in range(1, N + 1):
        for j in range(1, i + 1):
            tbl[i][j] = j * tbl[i - 1][j] + tbl[i - 1][j - 1]
    print("n\\k", " ".join(f"{j:>6}" for j in range(1, N + 1)))
    for i in range(1, N + 1):
        row = " ".join(f"{tbl[i][j]:>6}" if j <= i else "     -" for j in range(1, N + 1))
        bell = sum(tbl[i][1:i + 1])
        print(f" {i} ", row, f" | Bell({i})={bell}")